import MagicString from 'magic-string';
import { parseAst, type Plugin } from 'vite';

const DECORATE_HELPER = '@oxc-project/runtime/helpers/decorate';

type Node = { type: string; start: number; [key: string]: any };

/**
 * Vite 8 compiles decorators with oxc, which emits
 * `X = _decorate([..., _decorateMetadata("design:paramtypes",
 * [typeof Dep === "undefined" ? Object : Dep])], X)` for every Nest class.
 * The `undefined` side of that ternary can never run, so each injectable
 * class lost half a branch in the coverage report. Vitest already skips the
 * equivalent SWC helper (`_ts_decorate`); this plugin does the same for oxc
 * by marking those generated statements with `v8 ignore next`. Source code is
 * not affected, only the decorator wiring generated by the compiler.
 */
export function ignoreDecoratorCoverage(): Plugin {
  return {
    name: 'ignore-decorator-coverage',
    enforce: 'post',
    transform(code, id) {
      if (!/\/src\/.*\.ts$/.test(id) || !code.includes(DECORATE_HELPER)) {
        return null;
      }

      const program = parseAst(code) as unknown as { body: Node[] };
      const helpers = new Set<string>();
      for (const node of program.body) {
        if (
          node.type === 'ImportDeclaration' &&
          node.source.value === DECORATE_HELPER
        ) {
          for (const specifier of node.specifiers)
            helpers.add(specifier.local.name);
        }
      }

      // Classes that reference themselves get `X = _X = _decorate(...)`.
      const isDecorateCall = (expression: Node | undefined): boolean => {
        if (expression?.type === 'AssignmentExpression') {
          return isDecorateCall(expression.right);
        }
        return (
          expression?.type === 'CallExpression' &&
          expression.callee.type === 'Identifier' &&
          helpers.has(expression.callee.name)
        );
      };

      const output = new MagicString(code);
      for (const node of program.body) {
        if (
          node.type === 'ExpressionStatement' &&
          isDecorateCall(node.expression)
        ) {
          output.prependLeft(node.start, '/* v8 ignore next */ ');
        }
      }

      if (!output.hasChanged()) return null;
      return {
        code: output.toString(),
        map: output.generateMap({ hires: true }),
      };
    },
  };
}
